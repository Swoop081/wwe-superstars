// Builds v2/data/roster.js from v2/data/roster.json (the editable source of truth).
// roster.json entries: {n:name, a:art slug, p:tier, f:finisher, g:"M"|"F", s:[Power,Striking,Technique,Aerial,Submission,Charisma,StarPower]}
// Run from the repo root after editing roster.json or adding a Superstar:  node tools/v2-build-roster.cjs
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const roster = JSON.parse(fs.readFileSync(path.join(root, 'v2', 'data', 'roster.json'), 'utf8'));
const TIERS = ['Main Event', 'Upper Midcard', 'Midcard', 'Lower Midcard', 'Opener'];
const errors = [], seen = new Set();
for (const r of roster) {
  if (seen.has(r.n)) errors.push('duplicate name: ' + r.n); seen.add(r.n);
  if (!Array.isArray(r.s) || r.s.length !== 7 || r.s.some(v => !Number.isFinite(v) || v < 1 || v > 100)) errors.push(r.n + ': needs 7 stats between 1 and 100');
  if (!TIERS.includes(r.p)) errors.push(r.n + ': tier must be one of ' + TIERS.join(', '));
  if (!fs.existsSync(path.join(root, 'assets', 'superstars', r.a + '.webp'))) errors.push(r.n + ': missing assets/superstars/' + r.a + '.webp');
}
if (errors.length) { console.error(errors.join('\n')); process.exit(1); }
roster.sort((a, b) => a.n.localeCompare(b.n));
fs.writeFileSync(path.join(root, 'v2', 'data', 'roster.json'), '[\n' + roster.map(r => ' ' + JSON.stringify(r)).join(',\n') + '\n]\n');
fs.writeFileSync(path.join(root, 'v2', 'data', 'roster.js'),
  '// Generated by tools/v2-build-roster.cjs from roster.json - do not edit by hand.\n'
  + 'globalThis.ROSTER = ' + JSON.stringify(roster) + ';\n'
  + 'if (typeof module !== "undefined") module.exports = globalThis.ROSTER;\n');
console.log('built roster.js with', roster.length, 'Superstars');
