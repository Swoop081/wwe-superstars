// Builds v3/data/cards.js from v2/data/roster.json (the editable roster).
// Each card gets 5 base stats (Strength, Strike, Technical, Agility, Charisma), a rarity, a tag symbol and ring arrows.
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const roster = JSON.parse(fs.readFileSync(path.join(root, 'v2', 'data', 'roster.json'), 'utf8'));
const clamp = (v, a, b) => Math.max(a, Math.min(b, v));
const stretch = v => clamp(Math.round(70 + (v - 70) * 1.35), 30, 100);
const hash = s => { let h = 2166136261; for (const c of s) { h ^= c.charCodeAt(0); h = Math.imul(h, 16777619); } return h >>> 0; };
const TIER_BONUS = { 'Main Event': 6, 'Upper Midcard': 3, 'Midcard': 0, 'Lower Midcard': -3, 'Opener': -6 };
const raw = roster.map(r => { const [pw, st, te, ag, su, ch, sp] = r.s; return [0.85 * pw + 0.15 * st, 0.85 * st + 0.15 * pw, 0.5 * te + 0.5 * su, 0.85 * ag + 0.15 * st, 0.6 * ch + 0.4 * sp]; });
// Re-centre every stat on the same average (so Strength/Agility aren't always weaker than Strike/Charisma) and keep weaknesses
// gentle: nothing below 50, spread x1.15 instead of the old x1.35.
const mean = [0, 1, 2, 3, 4].map(i => raw.reduce((a, r) => a + r[i], 0) / raw.length);
const cards = roster.map((r, k) => {
  const s = raw[k].map((v, i) => clamp(Math.round(52 + (v - mean[i]) * 0.6), 38, 72));
  const h = hash(r.n);
  // 3-4 arrows out of 8 directions (N,NE,E,SE,S,SW,W,NW), deterministic per card
  const arrows = []; let x = h;
  while (arrows.length < 3 + (h % 2)) { x = Math.imul(x ^ (x >>> 13), 1274126177) >>> 0; const d = x % 8; if (!arrows.includes(d)) arrows.push(d); }
  return { n: r.n, a: r.a, g: r.g, f: r.f, s, sym: ['BL', 'BR', 'YU', 'YD'][h % 4], ar: arrows.sort(), score: s.reduce((p, c) => p + c, 0) / 5 + TIER_BONUS[r.p] };
});
// No rarities in the game. `rar` is kept only as a hidden star-power rank (used to pick bosses, prizes and weak loaner cards).
const cuts = [0.18, 0.18, 0.18, 0.14, 0.12, 0.09, 0.06, 0.03, 0.02];
const order = cards.map((c, i) => i).sort((a, b) => cards[a].score - cards[b].score);
let at = 0;
cuts.forEach((p, rar) => { const n = rar === cuts.length - 1 ? order.length - at : Math.round(p * order.length); order.slice(at, at + n).forEach(i => { cards[i].rar = rar; }); at += n; });
cards.forEach(c => delete c.score);
cards.sort((a, b) => a.n.localeCompare(b.n));
// Street Fighter movie tie-in: appended AFTER the sorted roster so existing saves (which store card indices) keep working.
// Stronger than the normal roster (base mid-60s). `mv` marks them: shown in the SF arcade name font and gated in packs by engine.js (T.movieEnd).
const MOVIE = [ // name, art file, gender, finisher, [STR, STK, TEC, AGI, CHA]
  ['Ryu', 'ryu', 'M', 'HADOKEN', [66, 74, 70, 66, 60]], ['Ken Masters', 'ken-masters', 'M', 'SHORYUKEN', [62, 72, 64, 68, 76]],
  ['Chun-Li', 'chun-li', 'F', 'LIGHTNING KICK', [58, 70, 66, 80, 64]], ['Guile', 'guile', 'M', 'SONIC BOOM', [72, 76, 62, 56, 64]],
  ['Zangief', 'zangief', 'M', 'SPINNING PILEDRIVER', [82, 66, 50, 50, 62]], ['Dhalsim', 'dhalsim', 'M', 'YOGA FLAME', [52, 60, 80, 66, 68]],
  ['Blanka', 'blanka', 'M', 'ELECTRIC THUNDER', [74, 68, 48, 78, 52]], ['E. Honda', 'e-honda', 'M', 'HUNDRED HAND SLAP', [80, 70, 50, 46, 66]],
  ['Balrog', 'balrog', 'M', 'DASH PUNCH', [74, 80, 52, 60, 62]], ['Vega', 'vega', 'M', 'CLAW ROLL', [56, 68, 72, 80, 74]],
  ['M. Bison', 'm-bison', 'M', 'PSYCHO CRUSHER', [70, 70, 74, 60, 82]], ['Cammy', 'cammy', 'F', 'SPIRAL ARROW', [60, 72, 70, 78, 62]],
  ['Akuma', 'akuma', 'M', 'RAGING DEMON', [78, 82, 66, 70, 56]], ['Joe', 'joe', 'M', 'KNOCKOUT BLOW', [66, 66, 62, 64, 64]]
].map(([n, a, g, f, s]) => {
  const h = hash(n), arrows = []; let x = h;
  while (arrows.length < 4) { x = Math.imul(x ^ (x >>> 13), 1274126177) >>> 0; const d = x % 8; if (!arrows.includes(d)) arrows.push(d); }
  return { n, a, g, f, s, sym: ['BL', 'BR', 'YU', 'YD'][h % 4], ar: arrows.sort(), rar: 6, mv: 1 };
});
cards.push(...MOVIE);
fs.writeFileSync(path.join(root, 'v3', 'data', 'cards.js'),
  '// Generated by tools/v3-build-cards.cjs from v2/data/roster.json - do not edit by hand.\nglobalThis.CARDS = ' + JSON.stringify(cards) + ';\nif (typeof module !== "undefined") module.exports = globalThis.CARDS;\n');
const cnt = {}; cards.forEach(c => cnt[c.rar] = (cnt[c.rar] || 0) + 1);
console.log('built', cards.length, 'cards; per rarity', JSON.stringify(cnt));
